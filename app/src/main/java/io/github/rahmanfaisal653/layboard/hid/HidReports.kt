package io.github.rahmanfaisal653.layboard.hid

/** HID report descriptor and report builders for a combined keyboard + relative mouse. */
object HidReports {
    const val ID_KEYBOARD = 1
    const val ID_MOUSE = 2

    const val BUTTON_LEFT = 0x01
    const val BUTTON_RIGHT = 0x02

    const val MOD_CTRL = 0x01
    const val MOD_SHIFT = 0x02
    const val MOD_ALT = 0x04
    const val MOD_GUI = 0x08

    private val DESCRIPTOR_INTS = intArrayOf(
        // Keyboard: 1 modifier byte, 1 reserved byte, 6 key slots.
        0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, ID_KEYBOARD,
        0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01,
        0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
        0x95, 0x01, 0x75, 0x08, 0x81, 0x01,
        0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65,
        0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00,
        0xC0,
        // Mouse: 3 buttons, relative X and Y. No wheel on purpose.
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, ID_MOUSE,
        0x09, 0x01, 0xA1, 0x00,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01,
        0x95, 0x03, 0x75, 0x01, 0x81, 0x02,
        0x95, 0x01, 0x75, 0x05, 0x81, 0x01,
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x15, 0x81, 0x25, 0x7F,
        0x75, 0x08, 0x95, 0x02, 0x81, 0x06,
        0xC0, 0xC0,
    )

    val DESCRIPTOR: ByteArray = ByteArray(DESCRIPTOR_INTS.size) { DESCRIPTOR_INTS[it].toByte() }

    /** Keyboard report body (without the report ID). A usage of 0 means "no key pressed". */
    fun keyboard(modifiers: Int, usage: Int): ByteArray =
        byteArrayOf(modifiers.toByte(), 0, usage.toByte(), 0, 0, 0, 0, 0)

    /** Mouse report body (without the report ID). dx and dy must be within -127..127. */
    fun mouse(buttons: Int, dx: Int, dy: Int): ByteArray =
        byteArrayOf(buttons.toByte(), dx.toByte(), dy.toByte())
}
